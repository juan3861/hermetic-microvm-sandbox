"""
GenesisLang Code Generator — Multi-backend
Backends: Python, JavaScript
"""

class CodeGen:
    def __init__(self, backend="python"):
        self.backend = backend
        self.indent = 0

    def i(self, s=""):
        return "    " * self.indent + s

    def generate(self, node):
        method = getattr(self, f"_gen_{node.kind}", None)
        if method is None:
            raise NotImplementedError(f"No generator for {node.kind}")
        return method(node)

    # ═══════════════════════════════════════════════
    # Program
    # ═══════════════════════════════════════════════
    def _gen_Program(self, node):
        lines = []
        if self.backend == "python":
            lines.append("# Generated by GenesisLang Compiler")
            lines.append("# -*- coding: utf-8 -*-")
            lines.append("")
            for s in node.stmts:
                lines.append(self.generate(s))
            lines.append('if __name__ == "__main__":')
            lines.append('    main()')
            lines.append("")
        elif self.backend == "javascript":
            lines.append("// Generated by GenesisLang Compiler")
            for s in node.stmts:
                lines.append(self.generate(s))
            lines.append("main();")
        return "\n".join(lines)

    # ═══════════════════════════════════════════════
    # Statements
    # ═══════════════════════════════════════════════
    def _gen_FnDef(self, node):
        params = ", ".join(node.params)
        lines = [self.i(f"def {node.name}({params}):")]
        self.indent += 1
        for s in node.body:
            lines.append(self.generate(s))
        self.indent -= 1
        lines.append("")
        return "\n".join(lines)

    def _gen_Let(self, node):
        val = self.generate(node.value)
        return self.i(f"{node.name} = {val}")

    def _gen_Assign(self, node):
        val = self.generate(node.value)
        return self.i(f"{node.name} = {val}")

    def _gen_If(self, node):
        cond = self.generate(node.cond)
        lines = [self.i(f"if {cond}:")]
        self.indent += 1
        for s in node.then_block:
            lines.append(self.generate(s))
        self.indent -= 1
        if node.else_block:
            lines.append(self.i("else:"))
            self.indent += 1
            for s in node.else_block:
                lines.append(self.generate(s))
            self.indent -= 1
        return "\n".join(lines)

    def _gen_For(self, node):
        start = self.generate(node.start)
        end = self.generate(node.end)
        lines = [self.i(f"for {node.var} in range({start}, {end}):")]
        self.indent += 1
        for s in node.body:
            lines.append(self.generate(s))
        self.indent -= 1
        return "\n".join(lines)

    def _gen_While(self, node):
        cond = self.generate(node.cond)
        lines = [self.i(f"while {cond}:")]
        self.indent += 1
        for s in node.body:
            lines.append(self.generate(s))
        self.indent -= 1
        return "\n".join(lines)

    def _gen_Return(self, node):
        if node.value:
            return self.i(f"return {self.generate(node.value)}")
        return self.i("return")

    def _gen_Emit(self, node):
        val = self.generate(node.value)
        return self.i(f"print({val})")

    def _gen_FnCall(self, node):
        args = ", ".join(self.generate(a) for a in node.args)
        return f"{node.name}({args})"

    def _gen_MethodCall(self, node):
        args = ", ".join(self.generate(a) for a in node.args)
        return f"{node.obj}.{node.method}({args})"

    def _gen_Member(self, node):
        return f"{node.obj}.{node.member}"

    # ═══════════════════════════════════════════════
    # Expressions
    # ═══════════════════════════════════════════════
    def _gen_BinaryOp(self, node):
        left = self.generate(node.left)
        right = self.generate(node.right)
        return f"({left} {node.op} {right})"

    def _gen_UnaryOp(self, node):
        op = node.op
        operand = self.generate(node.operand)
        return f"({op}{operand})"

    def _gen_Var(self, node):
        return node.name

    def _gen_Int(self, node):
        return str(node.value)

    def _gen_String(self, node):
        return f'"{node.value}"'

    def _gen_Bool(self, node):
        return "True" if node.value else "False"

    def _gen_List(self, node):
        items = ", ".join(self.generate(i) for i in node.items)
        return f"[{items}]"

    def _gen_Null(self, node):
        return "None"


def generate_python(ast):
    return CodeGen(backend="python").generate(ast)


def generate_javascript(ast):
    return CodeGen(backend="javascript").generate(ast)
